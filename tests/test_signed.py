# Generated by the server (pawdelta-web scripts/gen_signing_vectors.py) from
# seeded TEST keys; copied here unchanged.
VECTORS = json.loads((Path(__file__).parent / "fixtures" / "signing_vectors.json").read_text())
SEED = b"brindle signing test vector key (test only): "
VERDICTS = {"ok": None, "expired": signed.Expired, "wrong_type": signed.WrongType,
            "revoked": signed.Revoked, "unknown_kid": signed.UnknownKey,
            "bad_signature": signed.BadSignature, "claim_mismatch": signed.ClaimMismatch}


@pytest.fixture
def vector_keys():
    """Trust the vectors' test keys, as pinned keys would be."""
    with ExitStack() as stack:
        for kid, raw in VECTORS["keys"].items():
            pub = base64.urlsafe_b64decode(raw + "=" * (-len(raw) % 4))
            stack.enter_context(signed._test_signing_key(kid, Ed25519PublicKey.from_public_bytes(pub)))
        yield


@pytest.mark.parametrize("vector", VECTORS["vectors"], ids=[v["name"] for v in VECTORS["vectors"]])
def test_signing_vectors(vector_keys, vector):
    def check():
        return signed.verify(vector["token"], vector["token_use"], vector["expect"],
                             now=VECTORS["now"])

    assert vector["typ"] == signed.header_typ(vector["token_use"])
    want = VERDICTS[vector["verdict"]]
    if want is signed.Revoked:
        check()                           # valid until the revocation list arrives
    signed.save_revocations(VECTORS["revocations"])
    if want is None:
        assert check()["token_use"] == vector["token_use"]
        return
    with pytest.raises(want) as e:
        check()
    assert type(e.value) is want


def _vector_key(name):
    """A vectors test key, from the seed the server's generator uses."""
    key = Ed25519PrivateKey.from_private_bytes(hashlib.sha256(SEED + name.encode()).digest())
    x = b64(key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw))
    kid = license.jwk_thumbprint(x)
    assert VECTORS["keys"][kid] == x
    return key, kid


def test_stolen_active_key_drill(vector_keys):
    """The standby key revokes the active one, even after the cache has been
    filled with other revocations: everything the active key signed is
    refused, as revoked whatever else is wrong with it, and documents the
    standby key signs are accepted."""
    (active, active_kid), (standby, standby_kid) = _vector_key("active"), _vector_key("standby")
    assert (active_kid, standby_kid) == (VECTORS["active_kid"], VECTORS["standby_kid"])
    now = VECTORS["now"]

    def by(key, kid, doc_type, typ=None, **extra):
        payload = {"aud": "brindle-pro", "org_id": "org_vectors", "iat": now - 60, "exp": now + 3600,
                   "kid": kid, "token_use": doc_type, **extra}
        return sign(key, payload, {"typ": signed.header_typ(typ or doc_type), "kid": kid})

    n = signed.MAX_REVOCATIONS
    flood = ([by(standby, standby_kid, "revocation", revoked_kid=f"gone-{i}") for i in range(n)]
             + [by(standby, standby_kid, "revocation", revoked_kid="gone-0", jti=str(i)) for i in range(n)])
    assert len(signed.save_revocations(flood)) == n
    assert signed.save_revocations([by(standby, standby_kid, "revocation", revoked_kid=active_kid)]) \
        == {active_kid}
    old = [v for v in VECTORS["vectors"]
           if signed._json_object(signed._b64decode(v["token"].split(".")[0]))["kid"] == active_kid
           and v["verdict"] == "ok"]
    old.append({"token": by(active, active_kid, "status", typ="policy"), "token_use": "policy",
                "expect": {}})                                  # revoked, and the wrong token_use
    for v in old:
        with pytest.raises(signed.Revoked):
            signed.verify(v["token"], v["token_use"], v["expect"], now=now)
    assert signed.verify(by(standby, standby_kid, "policy"), "policy", {"org_id": "org_vectors"}, now=now)


@pytest.mark.parametrize("case", ["refresh", "held", "down"])
def test_an_entitlement_fetch_refreshes_the_revocation_list(backend, signing_key, case):
    """refresh: a direct refresh refuses the entitlement it fetches once the
    served list revokes its key. held: when the refresh then fails, the stored
    entitlement is checked against the new list. down: a failed fetch leaves
    the refresh working."""
    old, old_kid = Ed25519PrivateKey.generate(), "test-old"
    signer, signer_kid, revoked = ((old, old_kid, TEST_KID) if case == "refresh"
                                   else (signing_key, TEST_KID, old_kid))
    revocation = sign(signer, {"aud": "brindle-pro", "kid": signer_kid, "token_use": "revocation",
                               "revoked_kid": revoked}, {"typ": "brindle-revocation+jwt", "kid": signer_kid})
    backend.routes["GET /keys/revocations"] = [auth.TransportError("down") if case == "down"
                                               else (200, {"revocations": [revocation]})]
    t, now = backend.issue(), time.time()
    creds = {"access_token": t["access_token"], "refresh_token": t["refresh_token"],
             "access_expires_at": now + 900, "base_url": BASE,      # held by the old key, due for refresh
             "entitlement": sign(old, claims(kid=old_kid, iat=int(now - 3000), exp=int(now + 600)))}
    if case == "held":
        creds["org_id"] = "org_2"                                 # the backend answers for org_1: refused
        backend.routes["GET /entitlement?org_id=org_2"] = backend._entitlement
    store = credentials.default_store()
    store.save(creds)
    client = auth.Client(BASE, backend)
    with signed._test_signing_key(old_kid, old.public_key()):
        if case == "refresh":
            with pytest.raises(signed.Revoked):
                auth.refresh(client, store, creds)
        elif case == "held":
            with pytest.raises(signed.Revoked):
                license.current(store=store, client=client)
        else:
            assert license.current(store=store, client=client).plan == "pro"
    assert "GET /keys/revocations" in backend.paths()

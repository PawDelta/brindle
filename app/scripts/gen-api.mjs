#!/usr/bin/env node
/* npm run gen:api [-- <api-schema.json> [<out.ts>]]: writes src/api/schema.ts from the
   engine's DTO schema (brindle/service/dto.py, exported as
   src/brindle/daemon/api-schema.json). Without an argument the schema is
   looked for in $BRINDLE_ENGINE (an engine checkout), then in the engine of
   this same repo (its root, above app/). The engine's {"models": ...}, pydantic's
   {"$defs": ...} and OpenAPI's {"components": {"schemas": ...}} layouts are
   all read; each definition
   becomes one exported interface named as the engine names the model. */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = resolve(HERE, "..");
const OUT = join(APP, "src/api/schema.ts");
const SCHEMA_IN_ENGINE = "src/brindle/daemon/api-schema.json";

const BANNER = `/* The engine's DTOs (brindle/service/dto.py) as TypeScript.
   Generated by \`npm run gen:api\` from the engine's ${SCHEMA_IN_ENGINE}:
   don't edit by hand, regenerate. */`;

/* The engine's own layout is {"api_version", "routes", "models"}: each model is
   pydantic's schema for it alone, carrying the models it nests in its own
   $defs. Those are lifted beside it (they're the same models, by name). */
/** @param {Record<string, any>} schema */
function definitions(schema) {
  const defs = schema.$defs ?? schema.definitions ?? schema.components?.schemas ?? schema.models;
  if (!defs || typeof defs !== "object" || Object.keys(defs).length === 0) {
    throw new Error("the schema has no $defs, definitions, components.schemas or models");
  }
  /** @type {Record<string, any>} */
  const out = {};
  /** @type {Record<string, any>} */
  const nested = {};
  for (const [name, def] of Object.entries(defs)) {
    const { $defs: inner, ...rest } = def;
    out[name] = rest;
    Object.assign(nested, inner);
  }
  for (const [name, def] of Object.entries(nested)) out[name] ??= def;
  return out;
}

/* Every $ref pointed at #/$defs/, and `title` dropped below each definition's
   root: the compiler turns a titled property into its own named alias
   (pydantic titles every field), which would clutter the output. The keys of
   a name map (`properties`: a field may well be called "title") are names,
   not keywords, so they're kept. */
const NAME_MAPS = new Set(["properties", "patternProperties", "$defs", "definitions"]);

/**
 * @param {any} node
 * @param {boolean} [nested]
 * @returns {any}
 */
function normalise(node, nested = false) {
  if (Array.isArray(node)) return node.map((n) => normalise(n, true));
  if (!node || typeof node !== "object") return node;
  /** @type {Record<string, any>} */
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title" && nested) continue;
    if (k === "$ref" && typeof v === "string") {
      out[k] = v.replace(/^#\/(definitions|components\/schemas)\//, "#/$defs/");
    } else if (NAME_MAPS.has(k) && v && typeof v === "object") {
      out[k] = Object.fromEntries(Object.entries(v).map(([name, s]) => [name, normalise(s, true)]));
    } else {
      out[k] = normalise(v, true);
    }
  }
  return out;
}

/** @param {Record<string, any>} schema  the engine's api-schema.json, parsed */
export async function generate(schema) {
  const defs = /** @type {Record<string, any>} */ ({});
  for (const [name, def] of Object.entries(definitions(schema))) {
    defs[name] = { ...normalise(def), title: name };
  }
  const names = Object.keys(defs).sort();
  const root = {
    title: "ApiSchema",
    description: "Every DTO the daemon serves, by name.",
    type: "object",
    properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
    required: names,
    $defs: defs,
  };
  return compile(/** @type {any} */ (root), "ApiSchema", {
    bannerComment: BANNER,
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
  });
}

/** @param {string | undefined} arg */
function findSchema(arg) {
  const candidates = arg
    ? [resolve(process.cwd(), arg)]
    : [
        ...(process.env.BRINDLE_ENGINE ? [join(process.env.BRINDLE_ENGINE, SCHEMA_IN_ENGINE)] : []),
        resolve(APP, "..", SCHEMA_IN_ENGINE),
      ];
  return { found: candidates.find((p) => existsSync(p)), candidates };
}

async function main() {
  const { found, candidates } = findSchema(process.argv[2]);
  if (!found) {
    console.error(`gen:api: no api schema at ${candidates.join(" or ")}.`);
    console.error("Pass its path (npm run gen:api -- <file>) or set BRINDLE_ENGINE to an engine checkout.");
    console.error(`${OUT} is left as it is.`);
    process.exit(1);
  }
  const out = process.argv[3] ? resolve(process.cwd(), process.argv[3]) : OUT;
  writeFileSync(out, await generate(JSON.parse(readFileSync(found, "utf8"))));
  console.log(`gen:api: wrote ${out} from ${found}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
